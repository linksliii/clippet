import AppKit
import CryptoKit
import ImageIO

struct ClassifiedContent {
    var kind: ClipKind
    var text: String?
    var data: Data?
    var paths: [String] = []
    var filename: String?
    var uti: String?
    var tags: [String] = []
    var preview: String = ""
    var byteSize: Int = 0
    var hash: String = ""
}

struct PasteboardSnapshot {
    let types: [String]
    let string: String?
    let pngData: Data?
    let tiffData: Data?
    let fileURLs: [URL]
    let color: NSColor?

    static func capture(_ pb: NSPasteboard) -> PasteboardSnapshot? {
        let types = pb.types?.map(\.rawValue) ?? []
        guard !types.isEmpty else { return nil }
        var urls: [URL] = []
        if types.contains(where: { $0.hasPrefix("public.file-url") || $0 == "NSFilenamesPboardType" }) {
            let opts: [NSPasteboard.ReadingOptionKey: Any] = [.urlReadingFileURLsOnly: true]
            urls = (pb.readObjects(forClasses: [NSURL.self], options: opts) as? [NSURL])?
                .map { $0 as URL } ?? []
        }
        var color: NSColor?
        if types.contains(where: { $0.hasPrefix("com.apple.cocoa.pasteboard.color") }) {
            color = pb.readObjects(forClasses: [NSColor.self], options: nil)?.first as? NSColor
        }
        return PasteboardSnapshot(
            types: types,
            string: pb.string(forType: .string),
            pngData: pb.data(forType: .png),
            tiffData: types.contains("public.tiff") ? pb.data(forType: .tiff) : nil,
            fileURLs: urls,
            color: color)
    }
}

enum ContentClassifier {

    private static let ignoredTypes: [String] = [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType",
        "com.agilebits.onepassword"
    ]

    static var ignoreTransientContent = true

    static func classify(_ s: PasteboardSnapshot) -> ClassifiedContent? {
        if ignoreTransientContent, s.types.contains(where: { ignoredTypes.contains($0) }) {
            return nil
        }
        if !s.fileURLs.isEmpty { return makeFileContent(s.fileURLs) }
        if let (data, uti) = imagePayload(from: s) { return makeImageContent(data, uti: uti, types: s.types) }
        if let color = s.color { return makeColorContent(color) }
        if let raw = s.string, !raw.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return makeTextContent(raw)
        }
        return nil
    }

    static let maxRawImageBytes = 32 * 1024 * 1024

    /// Returns the payload plus the UTI to write back with.
    /// Bytes are stored verbatim when they fit the budget: decoding and
    /// re-encoding a 144 MP image cost ~1 s and silently downscaled it.
    private static func imagePayload(from s: PasteboardSnapshot) -> (Data, String)? {
        if let png = s.pngData, !png.isEmpty {
            if png.count <= maxRawImageBytes { return (png, "public.png") }
            return ImageNormalizer.normalize(png).map { ($0, "public.png") }
        }
        guard let tiff = s.tiffData, !tiff.isEmpty else { return nil }
        if tiff.count <= maxRawImageBytes { return (tiff, "public.tiff") }
        return ImageNormalizer.normalize(tiff).map { ($0, "public.png") }
    }

    private static func makeFileContent(_ urls: [URL]) -> ClassifiedContent {
        let paths = urls.map(\.path)
        let names = urls.map(\.lastPathComponent)
        let title = names.count == 1 ? names[0] : "\(names.count) files"
        var c = ClassifiedContent(kind: .file)
        c.paths = paths
        c.filename = title
        c.preview = title
        c.text = paths.joined(separator: "\n")
        c.uti = "public.file-url"
        c.byteSize = paths.reduce(0) { $0 + fileSize($1) }
        c.tags = names.count > 1 ? ["multi-file"] : []
        c.hash = digest("file:" + paths.joined(separator: "|"))
        return c
    }

    private static func makeImageContent(_ data: Data, uti: String, types: [String]) -> ClassifiedContent {
        let size = imagePixelSize(data)
        var c = ClassifiedContent(kind: .image)
        c.data = data
        c.uti = uti
        c.byteSize = data.count
        if let s = size {
            c.preview = "Image \(Int(s.width))×\(Int(s.height))"
            c.filename = "Image \(Int(s.width))×\(Int(s.height))"
        } else {
            c.preview = "Image"
            c.filename = "Image"
        }
        c.tags = ["image"]
        c.hash = digest("image:" + SHA256.hash(data: data).description)
        return c
    }

    private static func makeColorContent(_ color: NSColor) -> ClassifiedContent {
        let hex = color.hexString
        var c = ClassifiedContent(kind: .color)
        c.text = hex
        c.preview = hex
        c.uti = "public.color"
        c.byteSize = hex.utf8.count
        c.tags = ["color"]
        c.hash = digest("color:" + hex)
        return c
    }

    private static func makeTextContent(_ raw: String) -> ClassifiedContent {
        let trimmed = raw.trimmingCharacters(in: .whitespacesAndNewlines)

        let sample = trimmed.count > 8192 ? String(trimmed.prefix(8192)) : trimmed
        let kind: ClipKind
        if looksLikeURL(sample) {
            kind = .link
        } else if isHexColor(sample) {
            kind = .color
        } else if looksLikeCode(sample) {
            kind = .code
        } else {
            kind = .text
        }

        var c = ClassifiedContent(kind: kind)
        c.text = raw
        c.preview = makePreview(trimmed)
        c.filename = makeTitle(trimmed, kind: kind)
        c.uti = "public.utf8-plain-text"
        c.byteSize = raw.utf8.count
        c.tags = detectTags(sample, kind: kind)
        c.hash = digest(kind.rawValue + ":" + raw)
        return c
    }

    private static func looksLikeURL(_ s: String) -> Bool {
        guard s.count < 2048, !s.contains(" ") else { return false }
        guard let url = URL(string: s), let scheme = url.scheme?.lowercased() else { return false }
        let allowed: Set<String> = ["http", "https", "ftp", "mailto", "file", "ssh"]
        guard allowed.contains(scheme) else { return false }
        if scheme == "http" || scheme == "https" {
            return url.host != nil
        }
        return true
    }

    private static func isHexColor(_ s: String) -> Bool {
        let t = s.hasPrefix("#") ? String(s.dropFirst()) : s
        guard t.count == 6 || t.count == 3 || t.count == 8 else { return false }
        return t.allSatisfy { $0.isHexDigit }
    }

    private static func looksLikeCode(_ s: String) -> Bool {
        guard s.count >= 8 else { return false }
        let indicators: [String] = ["func ", "def ", "class ", "import ", "const ", "let ", "var ",
                                   "function ", "return ", "=>", ";\n", "{\n", "</", "#include",
                                   "SELECT ", "SELECT\n", "<?xml", "package "]
        let hits = indicators.reduce(0) { $0 + (s.contains($1) ? 1 : 0) }
        if hits >= 2 { return true }

        let braces = s.filter { "{}();".contains($0) }.count
        return s.count > 40 && Double(braces) / Double(s.count) > 0.08
    }

    private static func makePreview(_ s: String) -> String {
        let flat = s.replacingOccurrences(of: "\r\n", with: "\n")
        let limit = 400
        return flat.count <= limit ? flat : String(flat.prefix(limit)) + "…"
    }

    private static func makeTitle(_ s: String, kind: ClipKind) -> String {
        if kind == .link { return s }
        let firstLine = s.split(separator: "\n", maxSplits: 1, omittingEmptySubsequences: true).first.map(String.init) ?? s
        let limit = 80
        return firstLine.count <= limit ? firstLine : String(firstLine.prefix(limit)) + "…"
    }

    private struct SensitivePattern {
        let name: String
        let regex: NSRegularExpression
    }

    private static let sensitivePatterns: [SensitivePattern] = {
        let specs: [(String, String)] = [
            ("private-key", "-----BEGIN [A-Z ]*PRIVATE KEY-----"),
            ("aws-key", "\\bAKIA[0-9A-Z]{16}\\b"),
            ("github-token", "\\bgh[pousr]_[A-Za-z0-9]{36,}\\b"),
            ("slack-token", "\\bxox[baprs]-[A-Za-z0-9-]{10,}\\b"),
            ("jwt", "\\beyJ[A-Za-z0-9_-]{8,}\\.eyJ[A-Za-z0-9_-]{8,}\\.[A-Za-z0-9_-]{8,}\\b"),
            ("bearer", "(?i)\\bbearer\\s+[A-Za-z0-9._-]{20,}"),
            ("password-assign", "(?i)\\b(password|passwd|pwd)\\s*[:=]\\s*\\S{3,}"),
            ("api-key-assign", "(?i)\\b(api[_-]?key|secret[_-]?key|access[_-]?token)\\s*[:=]\\s*\\S{8,}")
        ]
        return specs.compactMap { name, pattern in
            guard let re = try? NSRegularExpression(pattern: pattern, options: []) else { return nil }
            return SensitivePattern(name: name, regex: re)
        }
    }()

    private static let emailRegex = try! NSRegularExpression(
        pattern: "[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\\.[A-Za-z]{2,}", options: [])
    private static let phoneRegex = try! NSRegularExpression(
        pattern: "\\+?\\d[\\d\\s().-]{7,}\\d", options: [])

    private static func detectTags(_ s: String, kind: ClipKind) -> [String] {
        var tags: [String] = []
        let range = NSRange(s.startIndex..<s.endIndex, in: s)

        let sensitive = sensitivePatterns.first { $0.regex.firstMatch(in: s, options: [], range: range) != nil }
        if let hit = sensitive {
            tags.append("secret")
            tags.append(hit.name)

            return tags
        }

        if kind == .link { tags.append("url") }
        if kind == .code { tags.append("code") }

        if emailRegex.firstMatch(in: s, options: [], range: range) != nil { tags.append("email") }
        if phoneRegex.firstMatch(in: s, options: [], range: range) != nil, s.count <= 30 { tags.append("phone") }
        if s.hasPrefix("{") || s.hasPrefix("[") {
            if (try? JSONSerialization.jsonObject(with: Data(s.utf8))) != nil { tags.append("json") }
        }
        if isHexColor(s) { tags.append("color") }

        return tags
    }

    private static func digest(_ s: String) -> String {
        let h = SHA256.hash(data: Data(s.utf8))
        return h.map { String(format: "%02x", $0) }.joined()
    }

    private static func imagePixelSize(_ data: Data) -> CGSize? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              let props = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let w = props[kCGImagePropertyPixelWidth] as? Double,
              let h = props[kCGImagePropertyPixelHeight] as? Double else { return nil }
        return CGSize(width: w, height: h)
    }

    private static func fileSize(_ path: String) -> Int {
        (try? FileManager.default.attributesOfItem(atPath: path)[.size] as? Int) ?? 0
    }
}

extension NSColor {

    var hexString: String {
        guard let c = usingColorSpace(.sRGB) else { return "#000000" }
        let r = Int((c.redComponent * 255).rounded())
        let g = Int((c.greenComponent * 255).rounded())
        let b = Int((c.blueComponent * 255).rounded())
        return String(format: "#%02X%02X%02X", r, g, b)
    }
}
